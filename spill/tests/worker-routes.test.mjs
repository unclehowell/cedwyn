import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';

const worker = await readFile(new URL('../worker/index.js', import.meta.url), 'utf8');
const assets = await readFile(new URL('../worker/assets.js', import.meta.url), 'utf8');

test('Spill Worker accepts its installed datro route and redirects other hosts to apex', () => {
  assert.match(worker, /const SITE = 'https:\/\/bucklerfamily\.estate'/);
  assert.match(worker, /const WORKER_HOST = 'cedwyn-datro\.bucklerfamily\.estate'/);
  assert.match(worker, /u\.hostname !== WORKER_HOST/);
  assert.match(worker, /Response\.redirect\(SITE \+ p \+ u\.search, 301\)/);
  assert.doesNotMatch(worker, /cedwyn\.bucklerfamily\.estate/);
});

test('Spill page and its static assets are served before the generic site gateway', () => {
  const assetLookup = worker.indexOf('const rel = p.replace');
  const genericFetch = worker.indexOf('return fetch(req);', assetLookup);
  assert.notEqual(assetLookup, -1, 'must resolve app path to a bundled asset');
  assert.notEqual(genericFetch, -1, 'must fall through to generic site gateway only after asset lookup');
  assert.ok(assetLookup < genericFetch, 'asset lookup must precede generic fetch');
  assert.match(worker, /const a = ASSETS && ASSETS\[rel\]/);
  assert.match(worker, /if \(a\) return new Response\(a\.body/);
  assert.match(assets, /generated by scripts\/build_worker_assets\.py/);
  for (const asset of ['index.html', 'spill.css', 'spill.js', 'llms.txt', 'protocol.json']) {
    assert.ok(assets.includes('"' + asset + '"'), 'generated bundle missing ' + asset);
  }
});

test('public page assets use the apex origin and release version', () => {
  const marker = 'export default ';
  const raw = assets.slice(assets.indexOf(marker) + marker.length).trim().replace(/;$/, '');
  const parsed = JSON.parse(raw);
  const protocol = JSON.parse(parsed['protocol.json'].body);
  assert.equal(protocol.version, '1.1.3');
  assert.equal(protocol.page, 'https://cedwyn.bucklerfamily.estate/dartboard/spill/');
  assert.ok(parsed['llms.txt'].body.includes('https://cedwyn.bucklerfamily.estate/dartboard/spill/protocol.json'));
  assert.ok(!assets.includes('https://cedwyn.bucklerfamily.estate'));
});
