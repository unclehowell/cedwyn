#!/usr/bin/env python3
"""Build or verify the asset module imported by worker/index.js.

The deployed Worker serves its own fallback copies of the page, CSS, JS,
protocol and llms.txt until the static site release is available. Keep these
assets reproducible from the dedicated repository's source files.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "worker" / "assets.js"
FILES = (
    ("index.html", "text/html; charset=utf-8"),
    ("spill.css", "text/css; charset=utf-8"),
    ("spill.js", "application/javascript; charset=utf-8"),
    ("llms.txt", "text/plain; charset=utf-8"),
    ("protocol.json", "application/json; charset=utf-8"),
)


def build_assets() -> dict[str, dict[str, str]]:
    assets: dict[str, dict[str, str]] = {}
    for name, content_type in FILES:
        path = ROOT / name
        if not path.is_file():
            raise FileNotFoundError(f"Required source asset is missing: {path}")
        assets[name] = {
            "type": content_type,
            "body": path.read_text(encoding="utf-8"),
            "value": "",
        }
    return assets


def render_module(assets: dict[str, dict[str, str]]) -> str:
    payload = json.dumps(assets, ensure_ascii=False, separators=(",", ":"))
    return (
        "// generated by scripts/build_worker_assets.py from the dedicated repository root assets\n"
        f"export default {payload};\n"
    )


def check_module(actual: str, expected: dict[str, dict[str, str]]) -> bool:
    prefix = "export default "
    if not actual.startswith("// generated by scripts/build_worker_assets.py"):
        return False
    start = actual.find(prefix)
    if start < 0:
        return False
    raw = actual[start + len(prefix):].strip()
    if raw.endswith(";"):
        raw = raw[:-1].rstrip()
    try:
        return json.loads(raw) == expected
    except json.JSONDecodeError:
        return False


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if worker/assets.js is stale")
    args = parser.parse_args()

    assets = build_assets()
    expected = render_module(assets)

    if args.check:
        if not OUTPUT.is_file() or not check_module(OUTPUT.read_text(encoding="utf-8"), assets):
            print("worker/assets.js is missing or stale; run python3 scripts/build_worker_assets.py", file=sys.stderr)
            return 1
        print("worker/assets.js matches index.html, spill.css, spill.js, llms.txt and protocol.json")
        return 0

    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(expected, encoding="utf-8", newline="\n")
    print(f"wrote {OUTPUT.relative_to(ROOT)} ({OUTPUT.stat().st_size} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
